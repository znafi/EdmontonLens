"""Run the BigQuery SQL files in ``sql/`` and save sample output.

Usage (from the repo root, with GCP_PROJECT_ID and credentials set in .env):

    python -m scripts.bq_sql views      # (re)create views in sql/views/
    python -m scripts.bq_sql checks     # run sql/quality/*.sql, print + save results
    python -m scripts.bq_sql analysis   # run sql/analysis/*.sql, print + save results
    python -m scripts.bq_sql all

SQL files reference ``{{ds}}``, replaced with ``project.dataset`` at run time.
Sample output is written to ``sql/samples/<name>.md``.
"""

from __future__ import annotations

import sys
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

from backend.config import settings
from backend.etl.loaders.bigquery import get_client

SQL_DIR = Path(__file__).resolve().parent.parent / "sql"
SAMPLES_DIR = SQL_DIR / "samples"
SAMPLE_ROWS = 15


def render(path: Path) -> str:
    ds = f"{settings.gcp_project_id}.{settings.bigquery_dataset}"
    return path.read_text().replace("{{ds}}", ds)


def run_file(path: Path) -> pd.DataFrame:
    return get_client().query(render(path)).result().to_dataframe()


def save_sample(path: Path, df: pd.DataFrame) -> None:
    SAMPLES_DIR.mkdir(exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    body = df.head(SAMPLE_ROWS).to_markdown(index=False)
    (SAMPLES_DIR / f"{path.stem}.md").write_text(
        f"<!-- generated by scripts/bq_sql.py from {path.relative_to(SQL_DIR.parent)} -->\n"
        f"Run at {stamp}; {len(df)} row(s), showing up to {SAMPLE_ROWS}.\n\n{body}\n"
    )


def views() -> None:
    for path in sorted((SQL_DIR / "views").glob("*.sql")):
        get_client().query(render(path)).result()
        print(f"created view from {path.name}")


def queries(folder: str) -> pd.DataFrame | None:
    frames = []
    for path in sorted((SQL_DIR / folder).glob("*.sql")):
        df = run_file(path)
        save_sample(path, df)
        print(f"\n== {path.relative_to(SQL_DIR.parent)} ({len(df)} rows)")
        print(df.head(SAMPLE_ROWS).to_string(index=False))
        frames.append(df)
    return pd.concat(frames, ignore_index=True) if folder == "quality" and frames else None


def main(argv: list[str]) -> None:
    if not settings.bigquery_enabled:
        sys.exit("BigQuery is not configured (set GCP_PROJECT_ID and GOOGLE_APPLICATION_CREDENTIALS).")
    cmd = argv[1] if len(argv) > 1 else "all"
    if cmd in ("views", "all"):
        views()
    if cmd in ("checks", "all"):
        queries("quality")
    if cmd in ("analysis", "all"):
        queries("analysis")
    if cmd not in ("views", "checks", "analysis", "all"):
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv)
